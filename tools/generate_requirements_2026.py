"""new-case: lossless public 2026 requirement CSVs to reproducible Markdown, not vendor code.

LP change markers follow the vendor comparison column (nonempty except есть/0).
HP markers compare short titles where an old title exists; these are editorial
V4 alignment hints, not a legal or semantic diff. Blank old titles are unclassified.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import html
import io
import os
from pathlib import Path
import tempfile

TITLE = "Наименование краткое (новая редакция)"
TEXT = "Описание (новая редакция)"
NUMBER = "Пункт требований"
COMPARE = "Сравнение с новой редакцией"
OLD_TITLE = "Наименование краткое (старая редакция)"


def cell(value: str) -> str:
    return html.escape(value, quote=False).replace("|", "&#124;").replace("\r\n", "\n").replace("\r", "\n").replace("\n", "<br>")


def read_rows(data: bytes, side: str) -> list[dict]:
    auto = "Авто" if side == "lp" else "Автоматизировано"
    comparison = COMPARE if side == "lp" else OLD_TITLE
    reader = csv.DictReader(io.StringIO(data.decode("utf-8-sig"), newline=""), delimiter=";", strict=True)
    required = {NUMBER, TITLE, TEXT, auto, comparison}
    if not reader.fieldnames or len(set(reader.fieldnames)) != len(reader.fieldnames) or not required <= set(reader.fieldnames):
        raise ValueError(f"{side}: missing or duplicate columns: {sorted(required)}")
    rows = []
    seen = set()
    for row in reader:
        if None in row or any(value is None for value in row.values()):
            raise ValueError(f"{side}: partial or extra CSV fields")
        number = row[NUMBER]
        if not number.strip() or number in seen:
            raise ValueError(f"{side}: empty or duplicate requirement {number!r}")
        if row[auto] not in {"0", "1"}:
            raise ValueError(f"{side}: invalid auto flag at {number}")
        seen.add(number)
        marker = row[comparison]
        changed = marker.strip() not in {"", "есть", "0"} if side == "lp" else bool(marker.strip()) and row[TITLE] != marker
        rows.append({"number": number, "title": row[TITLE], "text": row[TEXT], "auto": row[auto], "changed": changed})
    if not rows:
        raise ValueError(f"{side}: empty table")
    return rows


def same_file(left: Path, right: Path) -> bool:
    return left.resolve() == right.resolve() or (left.exists() and right.exists() and left.samefile(right))


def generate(source_dir: Path, output: Path, check: bool = False) -> list[str]:
    inputs = [source_dir / f"{side}_requirements_2026.csv" for side in ("lp", "hp")]
    paths = [*inputs, output]
    if any(same_file(a, b) for i, a in enumerate(paths) for b in paths[i + 1:]):
        raise ValueError("input/output paths must be distinct (including aliases)")
    snapshots = [p.read_bytes() for p in inputs]
    lines = ["# 2026 NPM / VPM requirement tables", "",
             "Generated by `python tools/generate_requirements_2026.py` from the public regulation text",
             "in SINTEZ AGR Checker 1.6.1 CSVs; no add-on code is copied. Russian source text is preserved.", "",
             "Regenerate: `python tools/generate_requirements_2026.py --source-dir C:/x/sintez/v1.6.1/documents --output docs/domain/requirements-2026.md`.",
             "Add `--check` to detect stale output without writing.", "",
             "`Auto` is the vendor flag, not our implementation coverage. All rows, including blank descriptions",
             "and `.` titles retained by the vendor, are included. See [validation](validation.md) for our coverage.", "",
             "`changed` is the #429 V4 editorial marker: LP comparison column nonempty except `есть`/`0`;",
             "HP short title differs from a nonempty old short title (blank old titles are unclassified).",
             "These markers include renumbering/removal and are not a complete semantic/legal diff.", "",
             "Project policy: [D160] VPM 512–1706 px/m, NPM 10–40 unchanged; [D161] OKS target 150,000",
             "versus regulation ceiling 1,000,000 triangles; [D162] both UCX gap rules; [D163] UKEP is",
             "the applicant's responsibility, missing signature file is information only.", ""]
    summaries = []
    for side, path, data in zip(("lp", "hp"), inputs, snapshots):
        rows = read_rows(data, side)
        summary = f"{side.upper()}: {len(rows)} rows, {sum(r['changed'] for r in rows)} changed"
        summaries.append(summary)
        lines += [f"## {side.upper()} ({'NPM' if side == 'lp' else 'VPM'})", "", summary, "",
                  f"Source: `{path.name}`, SHA-256 `{hashlib.sha256(data).hexdigest()}`.", "",
                  "| Requirement | Short title | Full text | Auto | V4 marker |",
                  "|---|---|---|---|---|"]
        for row in rows:
            lines.append("| " + " | ".join([cell(row['number']), cell(row['title']), cell(row['text']), row['auto'], 'changed' if row['changed'] else '—']) + " |")
        lines.append("")
    content = "\n".join(lines).encode("utf-8")
    if check:
        if output.read_bytes() != content:
            raise ValueError("generated output is stale")
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        # A unique sibling avoids clobbering predictable .partial names. Recheck the
        # source snapshot and aliases immediately before replacing the generated doc.
        name = None
        try:
            with tempfile.NamedTemporaryFile(dir=output.parent, prefix=output.name + ".", suffix=".partial", delete=False) as handle:
                name = Path(handle.name)
                handle.write(content)
            if snapshots != [p.read_bytes() for p in inputs] or any(same_file(output, p) for p in inputs):
                raise ValueError("source changed during generation or output aliases input")
            os.replace(name, output)
        finally:
            if name is not None:
                name.unlink(missing_ok=True)
    return summaries


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=Path("C:/x/sintez/v1.6.1/documents"))
    parser.add_argument("--output", type=Path, default=Path("docs/domain/requirements-2026.md"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        print("\n".join(generate(args.source_dir, args.output, args.check)))
    except (OSError, ValueError, csv.Error) as exc:
        parser.exit(1, f"error: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
