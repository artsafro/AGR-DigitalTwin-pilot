"""Independent synthetic plan fixtures for the roof-inset-plane checker.

Pattern: roof-inset-plane | new-case: direct inner-outline collapse/split controls.
Expected plate coordinates are specified independently, not generated by buffer
or the extractor. Buffers below only establish collapse/split preconditions.
Existing mesh QA covers narrow shafts and a combined vanish+split case using
buffer-derived plates; these isolate the contracts at inner_outlines_match.
"""

import pytest
from shapely.geometry import MultiPolygon, Polygon

from twinqa.geometry.checks import inner_outlines_match

OVERLAP = 0.1
WELD = 0.001
OUTER = [(0, 0), (12, 0), (12, 12), (0, 12)]
SHAFT = [(4, 4), (8, 4), (8, 8), (4, 8)]
INSET = [(4.1, 4.1), (7.9, 4.1), (7.9, 7.9), (4.1, 7.9)]
SECOND_SHAFT = [(1, 1), (3, 1), (3, 3), (1, 3)]
SECOND_INSET = [(1.1, 1.1), (2.9, 1.1), (2.9, 2.9), (1.1, 2.9)]


def _region(rings):
    """Validate every synthetic ring and the containing polygon."""
    for ring in rings:
        shaft = Polygon(ring)
        assert shaft.is_valid and not shaft.is_empty and shaft.area > 0
    region = Polygon(OUTER, rings)
    assert region.is_valid and not region.is_empty
    assert len(region.interiors) == len(rings)
    return region


def _matches(shafts, plate_holes):
    return inner_outlines_match(
        _region(shafts), _region(plate_holes), OVERLAP, WELD
    )


def test_square_shaft_matches_independently_specified_inset():
    assert _matches([SHAFT], [INSET]) is True


@pytest.mark.parametrize("shaft_start", range(4))
@pytest.mark.parametrize("plate_start", range(4))
@pytest.mark.parametrize(
    "shaft_reverse,plate_reverse",
    [(False, False), (False, True), (True, False), (True, True)],
)
def test_winding_and_cyclic_starts_do_not_change_match(
    shaft_start, plate_start, shaft_reverse, plate_reverse
):
    shaft = SHAFT[shaft_start:] + SHAFT[:shaft_start]
    plate = INSET[plate_start:] + INSET[:plate_start]
    if shaft_reverse:
        shaft = shaft[::-1]
    if plate_reverse:
        plate = plate[::-1]
    assert _matches([shaft], [plate]) is True


def test_well_separated_shafts_match_plate_holes_in_reverse_order():
    assert Polygon(SHAFT).distance(Polygon(SECOND_SHAFT)) > 2 * OVERLAP
    assert _matches([SHAFT, SECOND_SHAFT], [SECOND_INSET, INSET]) is True


@pytest.mark.parametrize(
    "plate_holes", [[], [INSET, SECOND_INSET]], ids=["omitted", "additional"]
)
def test_omitted_or_additional_plate_hole_fails(plate_holes):
    assert _matches([SHAFT], plate_holes) is False


@pytest.mark.parametrize("dx,expected", [(0.002, False), (0.0005, True)])
def test_correct_count_displaced_ring_respects_weld(dx, expected):
    displaced = [(x + dx, y) for x, y in INSET]
    assert _matches([SHAFT], [displaced]) is expected


def test_collapsed_shaft_is_not_silently_dropped():
    narrow = [(4, 4), (4.15, 4), (4.15, 8), (4, 8)]
    shaft = Polygon(narrow)
    assert shaft.is_valid
    assert shaft.bounds[2] - shaft.bounds[0] < 2 * OVERLAP
    # Preconditions only: the oracle remains the literal False below.
    assert shaft.buffer(-OVERLAP, join_style="mitre", mitre_limit=1e6).is_empty
    # Dropping the vanished ring would incorrectly accept zero plate holes.
    assert _matches([narrow], []) is False


@pytest.mark.parametrize(
    "plate_holes",
    [[[(1.1, 1.1), (2.9, 1.1), (2.9, 2.9), (1.1, 2.9)]], []],
    ids=["matching-ring-count", "dropped-split"],
)
def test_split_dumbbell_shaft_fails(plate_holes):
    # Two 2 x 2 m lobes, joined across x=[3,4] by a 0.1 m-wide bridge.
    dumbbell = [
        (1, 1), (3, 1), (3, 1.95), (4, 1.95), (4, 1), (6, 1),
        (6, 3), (4, 3), (4, 2.05), (3, 2.05), (3, 3), (1, 3),
    ]
    shaft = Polygon(dumbbell)
    assert shaft.is_valid and shaft.geom_type == "Polygon"
    assert 2.05 - 1.95 == pytest.approx(0.1)
    assert 2.05 - 1.95 < 2 * OVERLAP
    # Establish the actual split; never use its components as expected rings.
    shrunk = shaft.buffer(-OVERLAP, join_style="mitre", mitre_limit=1e6)
    assert shrunk.is_valid and not shrunk.is_empty
    assert isinstance(shrunk, MultiPolygon) and len(shrunk.geoms) == 2
    assert all(not part.is_empty and part.area > 0 for part in shrunk.geoms)
    hole, plate = _region([dumbbell]), _region(plate_holes)
    if plate_holes:
        assert len(hole.interiors) == len(plate.interiors) == 1
    assert inner_outlines_match(hole, plate, OVERLAP, WELD) is False
