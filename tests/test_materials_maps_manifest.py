"""library/materials/maps_v00N.json [D239]: rows are well-formed; files on the drive match when it is mounted."""
import hashlib
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "library/materials"
VERSIONS = ("v001", "v002")
MANIFESTS = {v: json.loads((LIB / f"maps_{v}.json").read_text(encoding="utf-8")) for v in VERSIONS}
DRIVE = Path(MANIFESTS["v001"]["root"])
MAPS = {"d", "o", "m", "r", "n", "erm", "mask"}
PROFILES = {"npm", "vpm", "flora_source", "d207"}
PREFIXES = ("materials/v001/", "materials/placeholders/v001/", "flora/v003/maps/")


def table_ids():
    ids = set()
    for name in ("materials_v002.json", "ground_v001.json"):
        ids |= {r["library_id"] for r in json.loads((LIB / name).read_text(encoding="utf-8"))["materials"]}
    return ids


def check_source(r, p):
    s = r["source"]
    if r["synthetic"]:  # generated by texture_surfaces.py: recipe recorded, nothing read
        assert s["generator"] == "tools/materials/texture_surfaces.py" and s["recipe"], p
        assert len(s["recipe_sha256"]) == 64, p
    elif "msg_id" in s:  # Telegram inbox original
        assert s["msg_id"] and len(s["sha256"]) == 64, p
    else:  # a file of one of our own projects
        assert s["file"] and s["project"] and len(s["sha256"]) == 64, p


@pytest.mark.parametrize("version", VERSIONS)
def test_rows_are_well_formed(version):
    manifest = MANIFESTS[version]
    rows = manifest["maps"]
    assert rows and manifest["decision"] == "D239" and manifest["version"] == version
    assert len({r["path"] for r in rows}) == len(rows)
    new = {r["library_id"]: r["key"] for r in manifest["new_library_ids"]}
    assert len(new) == len(manifest["new_library_ids"]), "a new library id is proposed twice"
    assert not set(new) & table_ids(), "a new library id collides with the tables"
    known = table_ids() | set(new)
    for r in rows:
        p = r["path"]
        assert p.startswith(PREFIXES) and p.endswith(".png") and p.isascii(), p
        assert r["map"] in MAPS and r["profile"] in PROFILES, p
        assert r["mode"] == "RGB" and r["width"] == r["height"], p
        if r["profile"] == "d207":  # master: one whole period at exactly 1000 px/m [D207]
            assert r["px_per_m"] == 1000.0 and r["px_per_m_basis"], p
        else:
            assert r["width"] & (r["width"] - 1) == 0, p
        assert len(r["sha256"]) == 64 and r["bytes"] > 0, p
        check_source(r, p)
        assert r["verdict"] and r["checks"] == "pass", p
        assert r["px_per_m"] is None or r["px_per_m_basis"], p  # never a size without its basis
        if r["library_id"] is not None:
            assert r["library_id"] in known, p
        if p.startswith("materials/v001/"):
            assert p.split("/")[2] == str(r["library_id"]), p  # materials\v001\<library_id>\
        if r["profile"] == "npm":
            assert r["bytes"] <= 3 * 1024 * 1024 and r["map"] != "n", p  # [D015], [D014]
        if p.startswith("materials/placeholders/"):
            assert r["width"] == {"npm": 128, "vpm": 256}[r["profile"]], p  # TEX-09 / TEX-12
        if r["profile"] == "vpm" and not p.startswith("materials/placeholders/"):
            assert r["width"] in (2048, 4096), p  # TEX-10


def test_v002_carries_v001_unchanged():
    v1, v2 = MANIFESTS["v001"], MANIFESTS["v002"]
    assert v2["base_manifest"] == "library/materials/maps_v001.json"
    assert v2["maps"][:len(v1["maps"])] == v1["maps"]
    assert v1["new_library_ids"] == v2["new_library_ids"][:len(v1["new_library_ids"])]


def test_v002_new_rows_follow_the_source_policy():
    """[D243]: own textures first, then generated; no external downloads."""
    new = MANIFESTS["v002"]["maps"][len(MANIFESTS["v001"]["maps"]):]
    assert new
    for r in new:
        s = r["source"]
        assert r["synthetic"] or "Desktop" in s.get("file", "") or "msg_id" in s, r["path"]
        if r["synthetic"]:
            assert r["profile"] != "d207" or r["d207"].startswith("ok"), r["path"]


@pytest.mark.parametrize("version", VERSIONS)
def test_skipped_maf_atlas_is_not_processed(version):
    manifest = MANIFESTS[version]
    skipped = {s["msg_id"] for s in manifest["skipped"]}
    assert {53407, 53408} <= skipped
    assert not {r["source"].get("msg_id") for r in manifest["maps"]} & skipped


@pytest.mark.skipif(not DRIVE.is_dir(), reason="AGR-assets drive not mounted")
@pytest.mark.parametrize("version", VERSIONS)
def test_files_on_drive_match_manifest(version):
    manifest = MANIFESTS[version]
    for r in manifest["maps"]:
        data = (DRIVE / r["path"]).read_bytes()
        assert len(data) == r["bytes"] and hashlib.sha256(data).hexdigest() == r["sha256"], r["path"]
    inbox = DRIVE / manifest["inbox"]
    items = {i["msg_id"]: i for i in json.loads((inbox / "manifest.json").read_text(encoding="utf-8"))["items"]}
    for msg in {r["source"]["msg_id"] for r in manifest["maps"] if "msg_id" in r["source"]}:  # originals untouched
        item = items[msg]
        assert hashlib.sha256((inbox / item["file"]).read_bytes()).hexdigest() == item["sha256"], item["file"]
    for f, h in {(r["source"]["file"], r["source"]["sha256"]) for r in manifest["maps"] if "file" in r["source"]}:
        if Path(f).is_file():  # own project sources untouched (only on the machine that holds them)
            assert hashlib.sha256(Path(f).read_bytes()).hexdigest() == h, f
