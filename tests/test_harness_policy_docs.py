def test_pr_template_trace_generation_preserves_evidence_and_card_footer(tmp_path):
    import subprocess
    import sys

    template = ROOT / ".github/pull_request_template.md"
    assert template.is_file(), "Provide a repository PR evidence template"
    original = template.read_text(encoding="utf-8")
    for heading in ("Summary", "Evidence", "Verification boundary", "Merge Danger", "Agent trace"):
        assert f"## {heading}\n" in original
    for required in ("invariant", "probe", "N/N", "RED", "GREEN", "not measured", "card"):
        assert required in original
    before, after = original.split("## Agent trace\n", 1)
    assert "<generated by tools/hooks/agent_trace.py" in after
    dest = tmp_path / "pr.md"
    footer = "Refs example/synthetic#123\n"  # Synthetic closing line, not a real issue.
    dest.write_text(original + "\n" + footer, encoding="utf-8")
    command = [sys.executable, str(ROOT / "tools/hooks/agent_trace.py"),
               "--usage-log", str(tmp_path / "absent.jsonl"),
               "--writer", "synthetic test writer", "--into", str(dest)]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    assert result.returncode == 0, result.stderr
    once = dest.read_text(encoding="utf-8")
    assert once.startswith(before)
    assert once.endswith("\n" + footer)
    trace = once.split("## Agent trace\n", 1)[1].split("\nRefs ", 1)[0]
    assert "<generated by" not in trace
    assert "- Sessions: not measured (no transcript)" in trace
    assert "- Hook denials: not measured (no transcript)" in trace
    fields = [line.split(":", 1)[0][2:] for line in trace.splitlines() if line.startswith("- ")]
    assert fields == ["Sessions", "Written by", "Subagents", "Skills", "Commands", "Hook denials",
                      "Retries", "Context at handover", "Duration", "Commits"]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    assert result.returncode == 0, result.stderr
    assert dest.read_text(encoding="utf-8") == once
