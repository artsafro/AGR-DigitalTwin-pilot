"""new-case: every sibling module that an agr_tools file loads by path must ship in the MZP and be required by install.ms.

Pure text scan, no pymxs. A module loaded by `Path(__file__).with_name('x.py')`, `os.path.join(<dir of __file__>, 'x.py')`
or a `_load*('x.py', ...)` helper call but missing from build_agr_tools.FILES or install.ms `required` fails only at
install time in 3ds Max (PR #1013 verification gap).
"""
import importlib.util
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / 'adapters/max/agr_tools'
NAME = r"['\"](\w+\.py)['\"]"
PATTERNS = (
    re.compile(r"with_name\(\s*" + NAME),
    re.compile(r"__file__[^\n]*?,\s*" + NAME),
    re.compile(r"\b_load\w*\(\s*" + NAME),
)


def _load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


builder = _load(ROOT / 'tools/max/build_agr_tools.py', 'agr_builder_sibling')


def collect(sources):
    """{module name: [referencing files]} from {file name: source text}."""
    found = {}
    for fname, text in sources.items():
        for pat in PATTERNS:
            for m in pat.finditer(text):
                found.setdefault(m.group(1), []).append(fname)
    return found


def required_of(install_text):
    m = re.search(r"local required = #\((.*?)\)\s*\n", install_text, re.S)
    assert m, 'install.ms has no `local required = #(...)` array'
    return set(re.findall(r'"([\w.\-]+)"', m.group(1)))


def problems(sources, existing, files, required):
    out = []
    for name, users in sorted(collect(sources).items()):
        if name not in existing:
            out.append(f'{name}: missing in adapters/max/agr_tools (used by {sorted(set(users))})')
        if name not in files:
            out.append(f'{name}: not in build_agr_tools.FILES or its generated entries')
        if name not in required:
            out.append(f'{name}: not quoted in install.ms required')
    return out


def _real():
    sources = {p.name: p.read_text(encoding='utf-8') for p in PKG.glob('*.py')}
    install = (PKG / 'install.ms').read_text(encoding='utf-8')
    # hygiene_core.py, uv_nudge_core.py, ucx_audit_core.py are generated by the builder from src/, not stored in PKG
    shipped = set(builder._collect()[0])
    return sources, {p.name for p in PKG.iterdir()} | shipped, set(builder.FILES) | shipped, required_of(install)


def test_collects_session_core_and_every_sibling_is_shipped_and_required():
    sources, existing, files, required = _real()
    assert 'session_core.py' in collect(sources)
    assert problems(sources, existing, files, required) == []


def test_removing_from_required_fails_naming_module():
    sources, existing, files, required = _real()
    res = problems(sources, existing, files, required - {'session_core.py'})
    assert any(r.startswith('session_core.py: not quoted') for r in res)


def test_ghost_sibling_reference_fails_naming_it():
    sources, existing, files, required = _real()
    sources['ghost_user.py'] = "spec = f(Path(__file__).with_name('ghost_core.py'))\n"
    res = problems(sources, existing, files, required)
    assert sum(r.startswith('ghost_core.py:') for r in res) == 3


@pytest.mark.parametrize('src', ["x = Path(__file__).with_name('a_core.py')",
                                 "p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'a_core.py')",
                                 "m = _load_core('a_core.py', 'x')"])
def test_each_reference_form_is_collected(src):
    assert set(collect({'u.py': src})) == {'a_core.py'}
