def test_context_map_function_typo_is_reported(tmp_path, capsys):
    root = _tmp_root(tmp_path)
    path = root / route_map.context_maps()["ground-contexts"]
    text = path.read_text(encoding="utf-8").replace("name: height_values", "name: height_valuez", 1)
    assert "height_valuez" in text
    path.write_text(text, encoding="utf-8")
    route_map.main(["--root", str(root)])
    capsys.readouterr()
    assert route_map.main(["--root", str(root), "--check"]) == 1
    assert "has no top-level function height_valuez" in capsys.readouterr().out


# ---------------------------------------------------------------- CLI fail-closed on a copy
def _tmp_root(tmp_path):
    shutil.copytree(ARCH, tmp_path / "docs/architecture")
    shutil.copy2(ROOT / "docs/decisions.md", tmp_path / "docs/decisions.md")
    cmap = _maps()["ground-contexts"]
    for c in [cmap["shared_kernel"]] + cmap["contexts"]:   # owners only: the function check needs the file
        (tmp_path / c["owner"]).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / c["owner"], tmp_path / c["owner"])
    return tmp_path


