@pytest.mark.parametrize("name,title", [("vpm-route", "ВПМ ОКС"), ("ground-route", "Ground")])
def test_every_red_box_is_explained_and_resolved_ones_are_gone(name, title):
    text = REPORT.read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(title)}\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    section = m.group(1)
    hot = {h["id"] for h in _routes()[name]["hotspots"]}
    status = dict(re.findall(r"^\| `([a-z0-9-]+)` \| (открыта|снята|обновлена) \|", section, re.M))
    assert set(status) == hot | RESOLVED[name], sorted(set(status) ^ (hot | RESOLVED[name]))
    assert {k for k, v in status.items() if v == "снята"} == RESOLVED[name]
    assert not hot & RESOLVED[name]
    for row in re.findall(r"^\| `[a-z0-9-]+` \| (?:открыта|снята|обновлена) \| (.*) \|$", section, re.M):
        assert len(row.strip()) > 15 and route_map.CYRILLIC.search(row)


