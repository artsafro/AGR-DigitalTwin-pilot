def test_context_map_yaml_as_output_is_refused(tmp_path, monkeypatch):
    shutil.copytree(ARCH, tmp_path / "docs/architecture")
    alias = tmp_path / "docs/architecture/ground-contexts.svg"
    alias.write_bytes((tmp_path / route_map.context_maps()["ground-contexts"]).read_bytes())
    before = alias.read_bytes()
    monkeypatch.setattr(route_map, "GROUND_CONTEXTS", Path("docs/architecture/ground-contexts.svg"))
    assert route_map.main(["--root", str(tmp_path)]) == 2
    assert alias.read_bytes() == before
    assert not list((tmp_path / "docs/architecture").glob("*.partial"))


